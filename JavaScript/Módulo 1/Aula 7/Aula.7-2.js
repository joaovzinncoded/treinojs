const notaDoJoao = 7
const notaDaMarina = "7"

// as constante são diferentes, um number e uma string, mas possuem o mesmo valor
//logo, "==" resulta em true

//as constantes possuem diferença de caractere de string e number
//logo, "===" resulta em false

console.log (notaDoJoao == notaDaMarina)
console.log (notaDoJoao === notaDaMarina)

console.log(notaDoJoao != notaDaMarina)
console.log(notaDoJoao !== notaDaMarina)

//as constantes tem valor igual a 7, logo "!=" que indica que elas não são iguais indica false
//as constantes não são iguais em algoritmo, pois uma é number e a outra string logo "!== indica" true

